// TestMVPHTTPAcceptance exercises real Gin handlers, SQL Server repositories,
// migrations, signed/revocable dev sessions and the mock AI through HTTP.
// It creates and drops ONLY its own random local database. No developer data
// or real mental-health disclosures may be used in this acceptance test.
func TestMVPHTTPAcceptance(t *testing.T) {
	if os.Getenv("WELLBEING_INTEGRATION") != "true" {
		t.Skip("requires WELLBEING_INTEGRATION=true and a local SQL Server")
	}
	if os.Getenv("APP_ENV") != "local" {
		t.Fatal("acceptance tests require APP_ENV=local")
	}
	raw := os.Getenv("DATABASE_URL")
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Scheme != "sqlserver" {
		t.Fatal("acceptance requires a sqlserver DATABASE_URL")
	}
	// Never accept an arbitrary remote SQL Server for a test that drops its own DB.
	if host := strings.ToLower(parsed.Hostname()); host != "127.0.0.1" && host != "localhost" && host != "mssql" {
		t.Fatal("acceptance requires a local SQL Server hostname")
	}
	dbName := "wellbeing_accept_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	query := parsed.Query()
	query.Set("database", dbName)
	parsed.RawQuery = query.Encode()
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	defer cancel()
	if err := database.EnsureLocalDatabase(ctx, parsed.String()); err != nil {
		t.Fatalf("create isolated acceptance DB: %v", err)
	}
	query.Set("database", "master")
	parsed.RawQuery = query.Encode()
	master, err := database.Connect(ctx, parsed.String())
	if err != nil {
		t.Fatalf("connect to local master for cleanup: %v", err)
	}
	var db *sql.DB
	t.Cleanup(func() {
		if db != nil {
			_ = db.Close()
		}
		cleanupCtx, stop := context.WithTimeout(context.Background(), 20*time.Second)
		defer stop()
		// dbName is generated by us with only ASCII letters and UUID hex digits.
		_, cleanupErr := master.ExecContext(cleanupCtx, "ALTER DATABASE ["+dbName+"] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE ["+dbName+"]")
		if cleanupErr != nil {
			t.Errorf("cleanup isolated acceptance DB: %v", cleanupErr)
		}
		_ = master.Close()
	})
	query.Set("database", dbName)
	parsed.RawQuery = query.Encode()
	db, err = database.Connect(ctx, parsed.String())
	if err != nil {
		t.Fatalf("connect isolated acceptance DB: %v", err)
	}
	migrationDir := filepath.Clean("../../db/migrations")
	if err := migrations.Apply(ctx, db, migrationDir); err != nil {
		t.Fatalf("apply migrations to isolated acceptance DB: %v", err)
	}
	cfg := config.Config{
		Environment: "local", AllowDevLogin: true,
		DevSessionSecret: strings.Repeat("local-synthetic-acceptance-test-secret-", 2),
		AllowedOrigin:    "http://127.0.0.1:5173",
		LLMProvider:      "mock", MaxContextMessages: 20, MaxContextChars: 16000,
	}
	handler, err := composition.NewAPI(cfg, db)
	if err != nil {
		t.Fatalf("compose HTTP API: %v", err)
	}
	server := httptest.NewServer(handler)
	defer server.Close()

	testerA := "11111111-1111-4111-8111-111111111111"
	testerB := "22222222-2222-4222-8222-222222222222"
	clientA, _ := newAcceptanceClient(t)
	clientB, jarB := newAcceptanceClient(t)

	acceptRequest(t, clientA, server.URL, "GET", "/health/live", nil, 200)
	acceptRequest(t, clientA, server.URL, "GET", "/health/ready", nil, 200)
	assertAcceptanceCode(t, acceptRequest(t, clientB, server.URL, "GET", "/api/v1/me", nil, 401), "SESSION_REQUIRED")
	users := acceptRequest(t, clientB, server.URL, "GET", "/api/v1/dev/users", nil, 200)
	if len(acceptArray(t, users, "items")) != 3 {
		t.Fatal("expected three synthetic dev users")
	}
	acceptRequest(t, clientA, server.URL, "POST", "/api/v1/dev/session", map[string]any{"userId": testerA}, 200)
	acceptRequest(t, clientB, server.URL, "POST", "/api/v1/dev/session", map[string]any{"userId": testerB}, 200)
	oldBCookies := jarB.Cookies(mustURL(t, server.URL+"/api/v1/me"))
	if len(oldBCookies) == 0 {
		t.Fatal("expected signed session cookie")
	}
	oldBToken := oldBCookies[0].Value // never log session material
	signer, err := devsecurity.NewSigner(cfg.DevSessionSecret, false)
	if err != nil {
		t.Fatal(err)
	}
	claims, err := signer.Verify(oldBToken, time.Now())
	if err != nil {
		t.Fatal("new session cookie was not valid")
	}
	t.Run("tampered expired legacy and unregistered cookies rejected over HTTP", func(t *testing.T) {
		legacyJSON, err := json.Marshal(map[string]any{"userId": testerB, "exp": time.Now().Add(time.Hour).Unix()})
		if err != nil {
			t.Fatal(err)
		}
		legacy := base64.RawURLEncoding.EncodeToString(legacyJSON)
		mac := hmac.New(sha256.New, []byte(cfg.DevSessionSecret))
		_, _ = mac.Write([]byte(legacy))
		legacy += "." + base64.RawURLEncoding.EncodeToString(mac.Sum(nil))
		for _, token := range []string{
			oldBToken + "tampered",
			signer.Issue(claims.UserID, claims.SessionID, time.Now().Add(-13*time.Hour)),
			legacy,
			signer.Issue(claims.UserID, uuid.New(), time.Now()),
		} {
			assertAcceptanceCode(t, acceptanceWithStolenCookie(t, server.URL, token), "SESSION_INVALID")
		}
		expiredID := uuid.New()
		if _, err := db.ExecContext(ctx, `INSERT INTO dbo.dev_sessions(id,user_id,expires_at)
            VALUES(CONVERT(uniqueidentifier,@p1),CONVERT(uniqueidentifier,@p2),DATEADD(second,-1,SYSUTCDATETIME()))`, expiredID.String(), testerB); err != nil {
			t.Fatal(err)
		}
		assertAcceptanceCode(t, acceptanceWithStolenCookie(t, server.URL, signer.Issue(claims.UserID, expiredID, time.Now())), "SESSION_INVALID")
	})

	if got := acceptString(t, acceptRequest(t, clientA, server.URL, "GET", "/api/v1/me", nil, 200), "userId"); got != testerA {
		t.Fatal("tester A resolved incorrectly")
	}
	beforeB := acceptRequest(t, clientB, server.URL, "GET", "/api/v1/me", nil, 200)
	if beforeB["onboardingCompletedAt"] != nil {
		t.Fatal("synthetic tester B must begin with incomplete onboarding")
	}
	assertAcceptanceCode(t, acceptRequest(t, clientB, server.URL, "POST", "/api/v1/conversations", map[string]any{}, 409), "ONBOARDING_REQUIRED")
	// An owned fixture created below the HTTP boundary cannot bypass the turn gate.
	beforeOnboardingID := uuid.NewString()
	if _, err := db.ExecContext(ctx, `INSERT INTO dbo.conversations(id,user_id) VALUES(CONVERT(uniqueidentifier,@p1),CONVERT(uniqueidentifier,@p2))`, beforeOnboardingID, testerB); err != nil {
		t.Fatal(err)
	}
	assertAcceptanceCode(t, acceptRequest(t, clientB, server.URL, "POST", "/api/v1/conversations/"+beforeOnboardingID+"/turns", map[string]any{
		"clientTurnId": uuid.NewString(), "message": "synthetic gate test",
	}, 409), "ONBOARDING_REQUIRED")
	assertMessages(t, acceptRequest(t, clientB, server.URL, "GET", "/api/v1/conversations/"+beforeOnboardingID+"/messages", nil, 200), 0)
	acceptRequest(t, clientB, server.URL, "DELETE", "/api/v1/conversations/"+beforeOnboardingID, nil, 204)
	t.Run("real HTTP cursor validation and concurrent next step", func(t *testing.T) {
		endpoint := "/api/v1/me/onboarding-progress"
		if acceptRequest(t, clientB, server.URL, "GET", endpoint, nil, 200)["furthestStep"] != float64(0) {
			t.Fatal("initial cursor")
		}
		for _, body := range []map[string]any{{"furthestStep": nil}, {"furthestStep": 1, "answers": map[string]any{"health": "synthetic"}}, {"furthestStep": 1, "userId": testerA}} {
			acceptRequest(t, clientB, server.URL, "PUT", endpoint, body, 400)
		}
		acceptRequest(t, clientB, server.URL, "PUT", endpoint, map[string]any{"furthestStep": 4}, 409)
		var wg sync.WaitGroup
		for i := 0; i < 8; i++ {
			wg.Add(1)
			go func() {
				defer wg.Done()
				acceptRequest(t, clientB, server.URL, "PUT", endpoint, map[string]any{"furthestStep": 1}, 200)
			}()
		}
		wg.Wait()
		if acceptRequest(t, clientB, server.URL, "PUT", endpoint, map[string]any{"furthestStep": 0}, 200)["furthestStep"] != float64(1) {
			t.Fatal("cursor decreased")
		}
		if acceptRequest(t, clientA, server.URL, "GET", endpoint, nil, 200)["furthestStep"] != float64(0) {
			t.Fatal("foreign cursor changed")
		}
	})
	invalid := map[string]any{"displayName": "  ", "conversationStyle": "guidance"}
	assertAcceptanceCode(t, acceptRequest(t, clientB, server.URL, "PATCH", "/api/v1/me/profile", invalid, 400), "VALIDATION_ERROR")
	if again := acceptRequest(t, clientB, server.URL, "GET", "/api/v1/me", nil, 200); again["onboardingCompletedAt"] != nil {
		t.Fatal("invalid profile edit completed onboarding")
	}
	profile := acceptRequest(t, clientB, server.URL, "PATCH", "/api/v1/me/profile", map[string]any{
		"displayName": "آزمایشگر ساختگی", "conversationStyle": "listening",
	}, 200)
	completion := acceptString(t, profile, "onboardingCompletedAt")
	if completion == "" || acceptString(t, profile, "conversationStyle") != "listening" {
		t.Fatal("onboarding did not persist expected profile")
	}
	edit := acceptRequest(t, clientB, server.URL, "PATCH", "/api/v1/me/profile", map[string]any{
		"displayName": "تستر دوم", "conversationStyle": "balanced",
	}, 200)
	if acceptString(t, edit, "onboardingCompletedAt") != completion {
		t.Fatal("editing profile changed original onboarding timestamp")
	}
	// An actual browser reload creates a new JS UI, not a new server session.
	// Reuse the cookie jar with a separate HTTP client to test persistence.
	afterReload := &http.Client{Jar: jarB, Timeout: 10 * time.Second}
	if got := acceptString(t, acceptRequest(t, afterReload, server.URL, "GET", "/api/v1/me", nil, 200), "displayName"); got != "تستر دوم" {
		t.Fatal("profile did not persist across client reload")
	}
	conversation := acceptRequest(t, afterReload, server.URL, "POST", "/api/v1/conversations", map[string]any{}, 201)
	conversationID := acceptString(t, conversation, "id")
	if _, err := uuid.Parse(conversationID); err != nil {
		t.Fatal("conversation ID is not UUID")
	}
	route := "/api/v1/conversations/" + conversationID
	t.Cleanup(func() { // best effort only; dropping isolated DB is authoritative cleanup
		acceptCleanupConversation(clientB, server.URL, route)
	})
	assertAcceptanceCode(t, acceptRequest(t, clientA, server.URL, "GET", route+"/messages", nil, 404), "RESOURCE_NOT_FOUND")
	assertAcceptanceCode(t, acceptRequest(t, clientA, server.URL, "DELETE", route, nil, 404), "RESOURCE_NOT_FOUND")
	assertAcceptanceCode(t, acceptRequest(t, clientA, server.URL, "POST", route+"/turns", map[string]any{
		"clientTurnId": uuid.NewString(), "message": "synthetic",
	}, 404), "RESOURCE_NOT_FOUND")

	id1 := uuid.NewString()
	body := map[string]any{"clientTurnId": id1, "message": "سلام، این یک پیام کاملاً ساختگی است."}
	result := acceptRequest(t, afterReload, server.URL, "POST", route+"/turns", body, 200)
	replay := acceptRequest(t, afterReload, server.URL, "POST", route+"/turns", body, 200)
	for _, key := range []string{"userMessageId", "assistantMessageId", "reply", "promptVersion"} {
		if acceptString(t, result, key) != acceptString(t, replay, key) {
			t.Fatalf("idempotent retry changed %s", key)
		}
	}
	if acceptString(t, result, "reply") == "" {
		t.Fatal("mock AI reply is empty")
	}
	assertAcceptanceCode(t, acceptRequest(t, afterReload, server.URL, "POST", route+"/turns", map[string]any{
		"clientTurnId": id1, "message": "changed synthetic input",
	}, 400), "VALIDATION_ERROR")
	acceptRequest(t, afterReload, server.URL, "POST", route+"/turns", map[string]any{
		"clientTurnId": uuid.NewString(), "message": "پیام ساختگی دوم",
	}, 200)
	assertMessages(t, acceptRequest(t, afterReload, server.URL, "GET", route+"/messages", nil, 200), 4)
	assertMessages(t, acceptRequest(t, clientB, server.URL, "GET", route+"/messages", nil, 200), 4)
	list := acceptArray(t, acceptRequest(t, clientB, server.URL, "GET", "/api/v1/conversations", nil, 200), "items")
	found := false
	for _, item := range list {
		if row, ok := item.(map[string]any); ok && row["id"] == conversationID {
			found = true
		}
	}
	if !found {
		t.Fatal("created conversation absent from history")
	}

	// Real HTTP bookmark lifecycle and ownership, against this disposable database.
	t.Run("bookmarks HTTP lifecycle and concurrent duplicate saves", func(t *testing.T) {
		userMessage := acceptString(t, result, "userMessageId")
		assistantMessage := acceptString(t, result, "assistantMessageId")
		for _, mid := range []string{userMessage, assistantMessage} {
			endpoint := "/api/v1/messages/" + mid + "/bookmark"
			acceptRequest(t, clientA, server.URL, "PUT", endpoint, nil, 404)
			acceptRequest(t, clientA, server.URL, "DELETE", endpoint, nil, 404)
			var wg sync.WaitGroup
			for i := 0; i < 8; i++ {
				wg.Add(1)
				go func() { defer wg.Done(); acceptRequest(t, clientB, server.URL, "PUT", endpoint, nil, 200) }()
			}
			wg.Wait()
		}
		items := acceptArray(t, acceptRequest(t, clientB, server.URL, "GET", "/api/v1/me/bookmarks", nil, 200), "items")
		if len(items) != 2 {
			t.Fatal("duplicate saves or missing user/assistant bookmark")
		}
		for _, raw := range items {
			item := raw.(map[string]any)
			if item["conversationId"] != conversationID || item["content"] == "" {
				t.Fatal("bookmark association corrupted")
			}
		}
		if len(acceptArray(t, acceptRequest(t, clientA, server.URL, "GET", "/api/v1/me/bookmarks", nil, 200), "items")) != 0 {
			t.Fatal("foreign bookmarks leaked")
		}
		for _, mid := range []string{"bad-id", uuid.NewString()} {
			status := 404
			if mid == "bad-id" {
				status = 400
			}
			for _, method := range []string{"PUT", "DELETE"} {
				acceptRequest(t, clientB, server.URL, method, "/api/v1/messages/"+mid+"/bookmark", nil, status)
			}
		}
		endpoint := "/api/v1/messages/" + userMessage + "/bookmark"
		acceptRequest(t, clientB, server.URL, "DELETE", endpoint, nil, 204)
		acceptRequest(t, clientB, server.URL, "DELETE", endpoint, nil, 204)
		if len(acceptArray(t, acceptRequest(t, clientB, server.URL, "GET", "/api/v1/me/bookmarks", nil, 200), "items")) != 1 {
			t.Fatal("idempotent unsave failed")
		}
	})

	// Provider outage must not store a phantom message or consume the turn ID.
	// Route this single synthetic turn through an unreachable local HTTPS provider.
	failingCfg := cfg
	failingCfg.LLMProvider = "openai-compatible"
	failingCfg.ModelAPIBaseURL = "https://127.0.0.1:1"
	failingCfg.ModelAPIKey = "synthetic-test-key"
	failingCfg.ModelName = "synthetic-model"
	failingCfg.ModelMaxOutputTokens = 256
	failingCfg.LLMTimeout = 2 * time.Second
	failingAPI, err := composition.NewAPI(failingCfg, db)
	if err != nil {
		t.Fatalf("compose failing-provider test API: %v", err)
	}
	failingServer := httptest.NewServer(failingAPI)
	defer failingServer.Close()
	retryID := uuid.NewString()
	retryBody := map[string]any{"clientTurnId": retryID, "message": "متن آزمایشی پس از خطای مدل"}
	assertAcceptanceCode(t, acceptRequest(t, clientB, failingServer.URL, "POST", route+"/turns", retryBody, 503), "AI_UNAVAILABLE")
	assertMessages(t, acceptRequest(t, clientB, server.URL, "GET", route+"/messages", nil, 200), 4)
	var failedRows int
	if err := db.QueryRowContext(ctx, `SELECT (SELECT COUNT(*) FROM dbo.turns WHERE id=CONVERT(uniqueidentifier,@p1))+
        (SELECT COUNT(*) FROM dbo.messages WHERE turn_id=CONVERT(uniqueidentifier,@p1))`, retryID).Scan(&failedRows); err != nil || failedRows != 1 {
		t.Fatalf("provider outage must retain only its reservation: count=%d error=%v", failedRows, err)
	}
	acceptRequest(t, clientB, server.URL, "POST", route+"/turns", retryBody, 200)
	assertMessages(t, acceptRequest(t, clientB, server.URL, "GET", route+"/messages", nil, 200), 6)

	// Switching identities revokes the old cookie, including replayed copies.
	acceptRequest(t, clientB, server.URL, "POST", "/api/v1/dev/session", map[string]any{"userId": testerA}, 200)
	if id := acceptString(t, acceptRequest(t, clientB, server.URL, "GET", "/api/v1/me", nil, 200), "userId"); id != testerA {
		t.Fatal("switch did not replace current session")
	}
	assertAcceptanceCode(t, acceptanceWithStolenCookie(t, server.URL, oldBToken), "SESSION_INVALID")
	assertAcceptanceCode(t, acceptRequest(t, clientB, server.URL, "GET", route+"/messages", nil, 404), "RESOURCE_NOT_FOUND")
	newACookies := jarB.Cookies(mustURL(t, server.URL+"/api/v1/me"))
	if len(newACookies) == 0 {
		t.Fatal("missing cookie after tester switch")
	}
	oldAToken := newACookies[0].Value
	acceptRequest(t, clientB, server.URL, "DELETE", "/api/v1/dev/session", nil, 204)
	assertAcceptanceCode(t, acceptRequest(t, clientB, server.URL, "GET", "/api/v1/me", nil, 401), "SESSION_REQUIRED")
	assertAcceptanceCode(t, acceptanceWithStolenCookie(t, server.URL, oldAToken), "SESSION_INVALID")

	// Original B ownership still works with a newly-issued synthetic session.
	acceptRequest(t, clientB, server.URL, "POST", "/api/v1/dev/session", map[string]any{"userId": testerB}, 200)
	assertMessages(t, acceptRequest(t, clientB, server.URL, "GET", route+"/messages", nil, 200), 6)
	other := acceptString(t, acceptRequest(t, clientB, server.URL, "POST", "/api/v1/conversations", nil, 201), "id")
	otherRoute := "/api/v1/conversations/" + other
	otherTurn := acceptRequest(t, clientB, server.URL, "POST", otherRoute+"/turns", map[string]any{"clientTurnId": uuid.NewString(), "message": "پیام ساختگی مستقل"}, 200)
	acceptRequest(t, clientB, server.URL, "PUT", "/api/v1/messages/"+acceptString(t, otherTurn, "assistantMessageId")+"/bookmark", nil, 200)
	acceptRequest(t, clientB, server.URL, "DELETE", route, nil, 204)
	remaining := acceptArray(t, acceptRequest(t, clientB, server.URL, "GET", "/api/v1/me/bookmarks", nil, 200), "items")
	if len(remaining) != 1 || remaining[0].(map[string]any)["conversationId"] != other {
		t.Fatal("soft deletion hid unrelated bookmark or exposed hidden history")
	}
	acceptRequest(t, clientB, server.URL, "DELETE", otherRoute, nil, 204)
	assertAcceptanceCode(t, acceptRequest(t, clientB, server.URL, "GET", route+"/messages", nil, 404), "RESOURCE_NOT_FOUND")
}

func newAcceptanceClient(t *testing.T) (*http.Client, http.CookieJar) {
	t.Helper()
	jar, err := cookiejar.New(nil)
	if err != nil {
		t.Fatal(err)
	}
	return &http.Client{Jar: jar, Timeout: 10 * time.Second}, jar
}

func mustURL(t *testing.T, raw string) *url.URL {
	t.Helper()
	parsed, err := url.Parse(raw)
	if err != nil {
		t.Fatal(err)
	}
	return parsed
}

func acceptRequest(t *testing.T, client *http.Client, base, method, route string, value any, expected int) map[string]any {
	t.Helper()
	var body []byte
	if value != nil {
		var err error
		body, err = json.Marshal(value)
		if err != nil {
			t.Fatal(err)
		}
	}
	req, err := http.NewRequest(method, base+route, bytes.NewReader(body))
	if err != nil {
		t.Fatal(err)
	}
	if value != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := client.Do(req)
	if err != nil {
		t.Fatalf("%s %s request failed: %v", method, route, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != expected {
		t.Fatalf("%s %s: status %d, want %d (response body redacted)", method, route, resp.StatusCode, expected)
	}
	if expected == http.StatusNoContent {
		return nil
	}
	var result map[string]any
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		t.Fatalf("%s %s: response is not JSON: %v", method, route, err)
	}
	return result
}

func acceptString(t *testing.T, result map[string]any, key string) string {
	t.Helper()
	v, ok := result[key].(string)
	if !ok {
		t.Fatalf("expected string field %s", key)
	}
	return v
}

func acceptArray(t *testing.T, result map[string]any, key string) []any {
	t.Helper()
	value, ok := result[key].([]any)
	if !ok {
		t.Fatalf("expected array field %s", key)
	}
	return value
}

func assertAcceptanceCode(t *testing.T, result map[string]any, expected string) {
	t.Helper()
	if result["code"] != expected {
		t.Fatalf("expected safe problem code %s", expected)
	}
}

func assertMessages(t *testing.T, result map[string]any, count int) {
	t.Helper()
	messages := acceptArray(t, result, "items")
	if len(messages) != count {
		t.Fatalf("message count: got %d, expected %d", len(messages), count)
	}
	for i, raw := range messages {
		message, ok := raw.(map[string]any)
		if !ok {
			t.Fatal("malformed message")
		}
		want := "user"
		if i%2 != 0 {
			want = "assistant"
		}
		if message["role"] != want {
			t.Fatalf("wrong history role at index %d", i)
		}
	}
}

func acceptanceWithStolenCookie(t *testing.T, base, token string) map[string]any {
	t.Helper()
	client := &http.Client{Timeout: 10 * time.Second}
	req, err := http.NewRequest("GET", base+"/api/v1/me", nil)
	if err != nil {
		t.Fatal(err)
	}
	req.AddCookie(&http.Cookie{Name: "wellbeing_dev_session", Value: token})
	resp, err := client.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != 401 {
		t.Fatalf("replayed revoked cookie accepted: status=%d", resp.StatusCode)
	}
	var result map[string]any
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		t.Fatal(err)
	}
	return result
}

func acceptCleanupConversation(client *http.Client, base, route string) {
	req, err := http.NewRequest("DELETE", base+route, nil)
	if err != nil {
		return
	}
	resp, err := client.Do(req)
	if err == nil {
		resp.Body.Close()
	}
}
