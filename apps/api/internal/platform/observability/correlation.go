package observability

import "context"

type requestIDKey struct{}
type turnRefKey struct{}

// WithRequestID carries the internally generated request ID, not an incoming
// untrusted header. It can cross HTTP, application and provider layers.
func WithRequestID(ctx context.Context, id string) context.Context {
	if !safeRequestID(id) {
		return ctx
	}
	return context.WithValue(ctx, requestIDKey{}, id)
}
func RequestID(ctx context.Context) string {
	if ctx == nil {
		return ""
	}
	id, _ := ctx.Value(requestIDKey{}).(string)
	if safeRequestID(id) {
		return id
	}
	return ""
}
func safeRequestID(s string) bool {
	if len(s) != 36 {
		return false
	}
	for i, c := range s {
		if i == 8 || i == 13 || i == 18 || i == 23 {
			if c != '-' {
				return false
			}
			continue
		}
		if c < '0' || c > '9' && c < 'a' || c > 'f' {
			return false
		}
	}
	return true
}
func CorrelationFields(ctx context.Context) []any {
	var result []any
	if id := RequestID(ctx); id != "" {
		result = append(result, "request_id", id)
	}
	if ref := TurnRefFromContext(ctx); ref != "" {
		result = append(result, "turn_ref", ref)
	}
	return result
}

// WithTurnRef accepts only the process-local, pseudonymous ref generated by
// TurnRef. Raw UUIDs, user IDs and conversation IDs are never logged.
func WithTurnRef(ctx context.Context, ref string) context.Context {
	if len(ref) != 16 {
		return ctx
	}
	for _, c := range ref {
		if c < '0' || c > '9' && c < 'a' || c > 'f' {
			return ctx
		}
	}
	return context.WithValue(ctx, turnRefKey{}, ref)
}
func TurnRefFromContext(ctx context.Context) string {
	if ctx == nil {
		return ""
	}
	ref, _ := ctx.Value(turnRefKey{}).(string)
	if len(ref) != 16 {
		return ""
	}
	return ref
}
